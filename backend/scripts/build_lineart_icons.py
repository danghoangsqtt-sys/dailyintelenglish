"""Phase 87.4: build backend/renderer/src/lineartIcons.ts from Tabler Icons (MIT) outline SVGs.

The roots Short draws a word's icons stroke by stroke when it has no Qwen picture. This script downloads the listed
outline icons once (network), keeps their inner elements and writes a TypeScript map; re-run it to change the list.
Usage: python backend/scripts/build_lineart_icons.py
"""

from __future__ import annotations

import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

VERSION = "v3.24.0"
BASE = f"https://raw.githubusercontent.com/tabler/tabler-icons/{VERSION}/icons/outline/"
LICENSE_URL = f"https://raw.githubusercontent.com/tabler/tabler-icons/{VERSION}/LICENSE"
NAMES = """
device-desktop folder file-zip arrow-down arrow-up arrow-right arrows-left-right arrows-maximize arrows-minimize
chart-line trending-down trending-up chart-bar door door-exit hand-finger hand-stop hand-click hand-grab message
messages speakerphone microphone headphones phone device-tv telescope eye eye-off search book books pencil writing notebook
file-text news lock lock-open key gift truck plane ship car bus building home school briefcase coin cash scale clock
hourglass calendar sun cloud-rain moon star heart mood-smile mood-sad bulb brain puzzle tool hammer settings box package
trash recycle droplet flame leaf plant tree world map compass flag trophy target rocket camera photo music palette brush
users user run walk bike ball-football shield shield-lock alert-triangle check x plus minus link unlink plug wifi battery
gauge ruler temperature microscope flask dna virus pill first-aid-kit gavel scissors magnet anchor stairs ladder
mailbox mail send inbox download upload refresh rotate switch-horizontal repeat ear volume eyeglass hand-love-you
lifebuoy mask presentation chalkboard certificate id dice paint
""".split()
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "backend" / "renderer" / "src" / "lineartIcons.ts"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 -- fixed GitHub raw URLs
        return response.read().decode("utf-8")


def inner(svg: str) -> str:
    """The drawing elements, without the invisible bounding-box path Tabler adds to every icon."""
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", body)
    return " ".join(body.split())


def main() -> int:
    icons: dict[str, str] = {}
    for name in NAMES:
        try:
            icons[name] = inner(fetch(BASE + f"{name}.svg"))
        except (urllib.error.HTTPError, AttributeError) as exc:
            print(f"skip {name}: {exc}", file=sys.stderr)
    (ROOT / "backend" / "renderer" / "LICENSE-tabler-icons.txt").write_text(fetch(LICENSE_URL), encoding="utf-8")
    OUT.write_text(
        "/**\n * Phase 87.4: line icons for the word-roots Short, drawn stroke by stroke when a word has no Qwen picture.\n"
        f" * Generated by backend/scripts/build_lineart_icons.py from Tabler Icons {VERSION} (MIT, backend/renderer/LICENSE-tabler-icons.txt).\n"
        " * Each value is the inner SVG of a 24x24 outline icon (stroke = currentColor).\n */\n"
        f"export const LINEART_ICONS: Record<string, string> = {json.dumps(icons, indent=1, sort_keys=True)};\n",
        encoding="utf-8")
    names = ROOT / "backend" / "content" / "data" / "lineart_icons.json"
    names.write_text(json.dumps(sorted(icons), indent=0) + "\n", encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
